def get_client_ip(request):
    """
    آی‌پی واقعی کاربر را برمی‌گرداند.

    عمداً فقط REMOTE_ADDR (آدرس واقعی اتصال TCP) استفاده می‌شود، نه هدر
    X-Forwarded-For — چون آن هدر را خودِ کلاینت هم می‌تواند ست کند و اگر
    بدون بررسی به آن اعتماد شود، محدودیت نرخ درخواست به‌سادگی دور زده
    می‌شود. اگر در آینده پشت یک ریورس‌پروکسی مطمئن (nginx/لود بالانسر) قرار
    گرفتید که این هدر را خودش بازنویسی می‌کند، این تابع باید متناسب با آن
    به‌روزرسانی شود.
    """
    return request.META.get("REMOTE_ADDR", "")
